# Fast reverse lookup mapping for symbol -> sector
_SYMBOL_TO_SECTOR: Dict[str, str] = {}
for sector, symbols in SP500_SECTORS.items():
    for sym in symbols:
        _SYMBOL_TO_SECTOR[sym.upper()] = sector
        if "." in sym:
            _SYMBOL_TO_SECTOR[sym.replace(".", "-").upper()] = sector
        elif "-" in sym:
            _SYMBOL_TO_SECTOR[sym.replace("-", ".").upper()] = sector


def get_sp500_sectors() -> Dict[str, List[str]]:
    """
    Returns a dictionary mapping all 11 GICS sectors
    to their respective S&P 500 constituent ticker symbols.
    """
    return {sector: list(symbols) for sector, symbols in SP500_SECTORS.items()}


def get_sp500_symbols(normalize_for_yf: bool = False) -> List[str]:
    """
    Returns a deduplicated, sorted list of all official S&P 500 symbols.
    If normalize_for_yf is True, dots are replaced with dashes (e.g. BRK.B -> BRK-B).
    """
    symbols = set()
    for sym_list in SP500_SECTORS.values():
        for s in sym_list:
            if normalize_for_yf:
                symbols.add(s.replace(".", "-"))
            else:
                symbols.add(s)
    return sorted(list(symbols))


def get_symbol_sector(symbol: str) -> Optional[str]:
    """
    Returns the GICS sector name for a given ticker symbol, or None if not found.
    Handles case insensitivity and dot/dash variations.
    """
    if not symbol:
        return None
    sym = symbol.strip().upper()
    return _SYMBOL_TO_SECTOR.get(sym) or _SYMBOL_TO_SECTOR.get(sym.replace(".", "-")) or _SYMBOL_TO_SECTOR.get(sym.replace("-", "."))


# Direct aliases for consistency across imports
def get_sp500_constituents(normalize_for_yf: bool = False) -> List[str]:
    return get_sp500_symbols(normalize_for_yf=normalize_for_yf)


def is_sp500_member(symbol: str) -> bool:
    return get_symbol_sector(symbol) is not None or symbol.upper().strip() in ("SPY", "VOO", "IVV", "^GSPC")


class SP500ConstituentProvider:
    @classmethod
    def get_constituents(cls, normalize_for_yf: bool = False, use_cache: bool = True) -> List[str]:
        return get_sp500_symbols(normalize_for_yf=normalize_for_yf)

    @classmethod
    def get_sectors(cls) -> Dict[str, List[str]]:
        return get_sp500_sectors()

    @classmethod
    def get_by_sector(cls, sector_name: str) -> List[str]:
        sectors = get_sp500_sectors()
        target = sector_name.lower().strip()
        for s_name, syms in sectors.items():
            if target in s_name.lower():
                return syms
        return []

    @classmethod
    def is_member(cls, symbol: str) -> bool:
        return is_sp500_member(symbol)
